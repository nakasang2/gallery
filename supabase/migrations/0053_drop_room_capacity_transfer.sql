-- 0052の「部屋間で枠を移動」を撤回する（ユーザー指摘 2026-08-11、DECISIONS 2026-08-11）
--
-- 背景: 0052で作った`transfer_room_capacity`（移動元/移動先/枚数を自分で指定して
-- 部屋間で`work_cap`を動かすRPC）を実際にUIへ出したところ、ユーザーから
-- 「移動とかややこしいので、共通扱いにしてほしい」との指摘。**部屋ごとに別々の
-- 数字を考えず、口座全体で1つの残り枠数だけを扱う**方式（本当の共通プール）に
-- 作り直すことにした。
--
-- 集計（口座内の全部屋の`work_cap`を合算する）は**アプリ側だけ**で行う
-- （`lib/limits.poolCapacityOf`）。DBスキーマ（`galleries.work_cap`列・等級ロジック・
-- 購入経路）は一切変えていない ── 部屋ごとの`work_cap`は購入・等級の記帳としては
-- そのまま残り、アプリが「合計」として読み替えるだけなので、DB側に新しい仕組みは
-- 要らない。よって0052で新設した移動用のRPCだけを不要として落とす。
--
-- `drop function if exists` なので、0052を本番に適用済みでも未適用でも安全に実行できる。
--
-- 適用方法: SQL Editor に貼り付けて Run(再実行安全)

drop function if exists public.transfer_room_capacity(uuid, uuid, int);
