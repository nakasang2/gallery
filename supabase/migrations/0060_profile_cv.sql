-- プロフィールに「来歴」を足す（ユーザー要望 2026-08-13）
-- 適用方法: SQL Editor に貼り付けて Run（再実行安全）
--
-- なぜ `bio` と別の欄にするか: 来歴（展示歴・受賞歴）は**箇条書きで積み上がっていく
-- 記録**で、読み物である自己紹介とは書き方も読まれ方も違う。1つの欄に混ぜると、
-- 3D の情報パネルで「自己紹介の続きに年号が延々と並ぶ」形になり、どちらも読みにくい。
-- 別列にすれば、パネルはタブで分けて出せる（展示情報／自己紹介／来歴）。
--
-- `not null default ''` は `bio` と同じ扱い。既存行はすべて空文字で埋まり、
-- アプリ側は「空なら来歴タブを出さない」で分岐する（空のタブを見せない）。
alter table public.profiles add column if not exists cv text not null default '';

comment on column public.profiles.cv is
  '来歴（展示歴・受賞歴）。自己紹介(bio)とは別欄。公開ページと3Dの情報パネルで、自己紹介と並ぶタブとして出す。';
