/** 明るさを「焼いたぶん」と「近くだけ実照明」に分ける比（DECISIONS 2026-08-19 ③）。
 *
 *  部屋のどの面にも同じ比で効かせるのが要点。焼いたライトマップ（`LightmapBaker`）は
 *  作品スポットの `1 - POOL_MIX` を運び、シーンに残る共有プール（`SpotPool`）の実照明が
 *  残りの `POOL_MIX` を出す。
 *  **地明かり（ambient / hemi）と環境マップは焼かない** ── 壁も床も実照明を見る材質の
 *  ままなので、今までどおり実物が効く。写して焼くと同じ値が2か所に増えるだけになる。
 *
 *  - `0` にすると全部焼く（照明 17個 → 2個・最速。ただし額の金属のハイライトが消える）
 *  - `1` にすると今日と同じ（焼き込みが効かない）
 *  見た目と速さの取引をこの1か所に集めてあるので、実機で見て決められる。
 *
 *  **葉のモジュールに置いてある。** `lightPlan` は `Exhibit` から採寸の関数を取り、
 *  `Exhibit` はこの比を要る ── 同じファイルに置くと循環 import になり、いつか誰かが
 *  モジュール直下でこの値を使った日に `ReferenceError: Cannot access 'POOL_MIX' before
 *  initialization` が出る（しかもバンドラの並べ方次第なので、開発では通って本番だけ落ちうる）。 */
export const POOL_MIX = 0.25
